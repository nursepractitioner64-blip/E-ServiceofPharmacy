const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/modules/branches/branches.service.js'), 'utf8');

test('branch management uses the existing BRANCH sheet as the canonical master', () => {
  assert.match(source, /const SHEET = 'BRANCH';/);
  assert.match(source, /const LEGACY_SHEET = 'BRANCHES';/);
  assert.match(source, /BRANCH_ID', 'BRANCH_CODE', 'BRANCH_NAME', 'STATUS', 'CREATED_AT', 'UPDATED_AT', 'REMARK'/);
});

test('legacy BRANCHES data is migrated by branch ID without deleting the legacy sheet or rewriting historical IDs', () => {
  assert.match(source, /Migrate the previously used BRANCHES master into BRANCH/);
  assert.match(source, /if \(seenIds\.has\(id\)\) continue;/);
  assert.match(source, /Preserve distinct IDs even if names match/);
  assert.doesNotMatch(source, /deleteSheet/);
});

test('new branch creation serializes concurrent requests and rejects duplicate names/codes', () => {
  assert.match(source, /function withMutationLock/);
  assert.match(source, /return withMutationLock\(async \(\) =>/);
  assert.match(source, /มีชื่อสาขานี้อยู่แล้ว/);
  assert.match(source, /รหัสสาขานี้มีอยู่แล้ว/);
});

test('only exact duplicate master rows are cleaned automatically; conflicting rows are preserved', () => {
  assert.match(source, /async function cleanupExactDuplicateIds/);
  assert.match(source, /fingerprints\.size !== 1/);
  assert.match(source, /จึงไม่ลบอัตโนมัติ/);
  assert.match(source, /BRANCH CLEANUP/);
});

test('Admin must provide a unique branch ID instead of receiving an autogenerated ID', () => {
  assert.match(source, /const id = clean\(input\.branchId \|\| input\.BRANCH_ID\)/);
  assert.match(source, /กรุณากำหนดรหัสสาขา/);
  assert.match(source, /BRANCH_ID\)\.toLowerCase\(\) === id\.toLowerCase\(\)/);
  assert.doesNotMatch(source, /crypto\.randomBytes/);
});

test('Admin can edit branch ID and the server updates branch references without touching vaccine sheets', () => {
  assert.match(source, /requestedId = input\.branchId/);
  assert.match(source, /async function collectBranchReferenceUpdates/);
  assert.match(source, /BRANCH_IDS/);
  assert.match(source, /vaccine\|vaccination\|immuniz/);
  assert.match(source, /if \(requestedId !== branchId\) \{/);
});


test('branch ID and known references are saved in one batchUpdate request', () => {
  assert.match(source, /async function collectBranchReferenceUpdates/);
  assert.match(source, /values\.batchUpdate\(/);
  assert.match(source, /BRANCH UPDATE SUCCESS/);
  assert.doesNotMatch(source, /replaceBranchReferences/);
});
